import assert from 'node:assert/strict';
import fs from 'node:fs';
import {renderProductPage,renderProductSitemap,productUrl} from '../lib/product-seo.js';

const p={id:'pABC123',name:'Wellness test product',category:'Body Care',description:'An example body-care product.',price:7000,salePrice:5000,stock:true,hidden:false,image:'https://res.cloudinary.com/example/image/upload/test.jpg'};
const html=renderProductPage(p);
assert.match(html,/<!doctype html>/);
assert.match(html,/<h1>Wellness test product<\/h1>/);
assert.match(html,/name="robots" content="index,follow"/);
assert.ok(html.includes('<link rel="canonical" href="'+productUrl(p.id)+'">'));
assert.match(html,/NGN/); // JSON-LD Offer must use the Nigerian naira.
assert.match(html,/add-to-cart|id="add"/);
const result=[...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
assert.equal(result.length,1);
const schema=JSON.parse(result[0][1]);
const product=schema['@graph'].find(x=>x['@type']==='Product');
assert.equal(product.name,p.name);
assert.equal(product.offers.price,5000);
assert.equal(product.offers.priceCurrency,'NGN');
assert.equal(product.offers.availability,'https://schema.org/InStock');
assert.equal(product.offers.url,productUrl(p.id));
assert.equal(schema['@graph'].find(x=>x['@type']==='BreadcrumbList').itemListElement.length,3);
assert.ok(!product.aggregateRating,'Store-level testimonials are not product reviews');
assert.equal(JSON.parse(html.match(/const id=("[^"]+")/)[1]),p.id);

const out=renderProductPage({...p,stock:false,salePrice:0,description:''});
assert.match(out,/Currently unavailable/);
assert.match(out,/OutOfStock/);
assert.match(out,/Ask the store for ingredients/);
assert.equal(JSON.parse(out.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'][0].offers.price,7000);
assert.throws(()=>renderProductPage({...p,hidden:true}));
assert.throws(()=>renderProductPage({...p,id:'a/b'}));
const hostile=renderProductPage({...p,name:'<script>alert("x")</script>'});
assert.ok(hostile.includes('&lt;script&gt;'));
assert.ok(!hostile.includes('<script>alert('));
const xml=renderProductSitemap([p,{...p,id:'pDEF456',name:'Another',stock:false},{...p,id:'pGHI789',name:'Hidden',hidden:true},p]);
assert.ok(xml.startsWith('<?xml'));
assert.equal((xml.match(/<url><loc>/g)||[]).length,2);
assert.ok(xml.includes(productUrl('pDEF456')));
assert.ok(!xml.includes('pGHI789'));
const vercel=JSON.parse(fs.readFileSync('vercel.json','utf8'));
assert.ok(vercel.rewrites.some(x=>x.source==='/products/:id'&&x.destination==='/api/product-page?id=:id'));
assert.ok(vercel.rewrites.some(x=>x.source==='/product-sitemap.xml'&&x.destination==='/api/product-sitemap'));
assert.ok(vercel.crons.some(x=>x.path==='/api/receipt-cleanup'),'Private receipt cleanup unchanged');
const robots=fs.readFileSync('robots.txt','utf8');
assert.match(robots,/^Sitemap: https:\/\/gdsparkandbloom\.com\.ng\/product-sitemap\.xml$/m);
assert.match(fs.readFileSync('site.js','utf8'),/href="\/products\/\$\{encodeURIComponent\(p\.id\)\}"/);
console.log('PASS | SSR Product JSON-LD uses genuine name, stock, price, image, canonical and NGN');
console.log('PASS | Hidden/invalid items excluded, scripts escaped, admin/cart/receipt flows unchanged');
console.log('PASS | Public product links and dynamic product sitemap configured');
