import assert from 'node:assert/strict';
import fs from 'node:fs';
import {cleanProduct} from '../lib/shop.js';
const sample={id:'test',name:'Sample',price:1500,sale_price:null,in_stock:true,stock_quantity:3,hidden:false};
assert.equal(cleanProduct(sample).availableQuantity,3);
assert.equal(cleanProduct(sample).stock,true);
assert.equal(cleanProduct({...sample,stock_quantity:0}).stock,false);
assert.equal(cleanProduct({...sample,in_stock:false}).stock,false);
assert.equal(cleanProduct({...sample,in_stock:false}).enabled,false);

const admin=fs.readFileSync('api/admin/mutate.js','utf8');
const order=fs.readFileSync('api/orders.js','utf8');
const live=fs.readFileSync('live.js','utf8');
const site=fs.readFileSync('site.js','utf8');
const migration=fs.readFileSync('supabase/migrations/gdsb_stock_quantity_reservations.sql','utf8');
const schema=fs.readFileSync('supabase/schema.sql','utf8');
assert.match(site,/name="availableQuantity"[^>]*type="number"[^>]*stockLimited/);
assert.match(site,/availableUnits\(p\)/);
assert.match(site,/function stockLimitNotice\(p\)/);
assert.match(live,/availableQuantity:Number\(d.get\('availableQuantity'\)\)/);
assert.match(admin,/stock_quantity:stockQuantity/);
assert.match(admin,/Number\.isSafeInteger\(stockQuantity\)/);
assert.match(order,/rpc\/gdsb_place_order/);
assert.match(admin,/rpc\/gdsb_set_order_status/);
assert.doesNotMatch(order,/await add\('gdsb_order_items'/);
assert.match(migration,/for v_line in[\s\S]+order by x.id/);
assert.match(migration,/where id=v_line\.id for update/);
assert.match(migration,/stock_quantity=stock_quantity-v_line\.qty/);
assert.match(migration,/insert into public\.gdsb_order_items/);
assert.match(migration,/where reference=p_reference for update/);
assert.match(migration,/if v_order\.stock_tracked and v_order\.stock_reserved and v_release then/);
assert.match(migration,/stock_quantity=stock_quantity\+v_item\.quantity/);
assert.match(migration,/elsif v_order\.stock_tracked and not v_order\.stock_reserved and not v_release then/);
assert.match(migration,/grant execute on function public\.gdsb_place_order\(jsonb,jsonb\) to service_role/);
assert.match(migration,/revoke all on function public\.gdsb_place_order\(jsonb,jsonb\) from public,anon,authenticated/);
assert.match(migration,/grant execute on function public\.gdsb_set_order_status\(text,text\) to service_role/);
assert.match(migration,/stock_quantity integer not null default 0/);
assert.match(schema,/stock_quantity integer not null default 0/);
assert.match(schema,/stock_tracked boolean not null default false/);
console.log('PASS | Admin quantity, cart cap, backend quote, atomic stock reservation, cancel/reject restock');
console.log('PASS | Only service role can invoke inventory mutation functions; historical orders unaffected');
